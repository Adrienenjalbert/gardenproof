/**
 * Deterministic MOCK provider used when no ANTHROPIC_API_KEY is set (demo mode) or when
 * AI_PROVIDER=mock (tests, evals). Same task names and output schemas as the real model.
 */
import type { EnrichmentDraft, JudgeResult } from "@/lib/content/drafts";
import { extractFacts } from "@/lib/content/lexicon";
import { joinList, withArticle } from "@/lib/content/text";
import type { AiTask, AiTaskData, EnrichmentTaskData } from "./tasks";
import { metricQuality } from "./images";
import { mockAdCopy, mockGbp, mockPortfolio, mockSeoArticle, mockSocial } from "./mock-copy";

export const DEMO_CHECK = { id: "demo-ai", ok: true, message: "Generated by demo mode (no API key)" } as const;

const SERVICE_BY_HEAD: [RegExp, string][] = [
  [/patio|terrace|paving/i, "patio_paving"],
  [/garden room|pergola|summerhouse|water feature|raised bed/i, "structures"],
  [/fenc|trellis|screening/i, "fencing"],
  [/pleached|hedg|border|planting/i, "planting"],
  [/lawn|turf/i, "lawn_turf"],
];

/** One kind of element -> that specialist service; a mix (pond + terrace + lawn) -> full design & build. */
function guessService(features: string[], known: string[]): string {
  const kinds = new Set(SERVICE_BY_HEAD.filter(([re]) => features.some((f) => re.test(f))).map(([, key]) => key));
  const fallback = known.includes("full_design") ? "full_design" : (known[0] ?? "full_design");
  if (kinds.size !== 1 || features.some((f) => /pond|rill/i.test(f))) return fallback;
  const [only] = kinds;
  return known.includes(only) ? only : fallback;
}

export function mockEnrichment(d: EnrichmentTaskData): EnrichmentDraft {
  const x = extractFacts(d.crewNotes);
  const images = d.images.map((i) => {
    const q = i.metrics ? metricQuality(i.metrics) : { score: 0.5, notes: ["image file unavailable"] };
    return {
      mediaId: i.mediaId,
      qualityScore: q.score,
      notes: [...q.notes, "people/plates not checked in demo mode"],
      peopleVisible: false,
      facesVisible: false,
      numberPlatesVisible: false,
      houseNumberVisible: false,
    };
  });
  const best = (stage: string) =>
    [...images]
      .filter((im) => d.images.find((i) => i.mediaId === im.mediaId)?.stage === stage)
      .sort((a, b) => b.qualityScore - a.qualityScore)[0]?.mediaId ?? null;
  const service = d.jobService && d.serviceKeys.includes(d.jobService) ? d.jobService : guessService(x.features, d.serviceKeys);
  return {
    service,
    subServices: [],
    features: x.features,
    materials: x.materials,
    plants: x.plants,
    durationDays: x.durationDays,
    challenge: x.challenge,
    result: x.features.length ? `Finished with ${joinList(x.features.slice(0, 4).map(withArticle))}.` : null,
    style: x.style,
    heroBeforeMediaId: best("before"),
    heroAfterMediaId: best("after"),
    confidence: x.features.length ? 0.6 : 0.2,
    images,
  };
}

/** The judge needs a real model; in mock mode it abstains with a neutral score. */
function mockJudge(): JudgeResult {
  return { premium: 3, reason: "Not judged in demo mode (no API key)." };
}

export function runMock<K extends AiTask>(task: K, data: AiTaskData[K]): unknown {
  switch (task) {
    case "enrichment":
      return mockEnrichment(data as AiTaskData["enrichment"]);
    case "portfolio_page":
      return mockPortfolio(data as AiTaskData["portfolio_page"]);
    case "ad_copy":
      return mockAdCopy(data as AiTaskData["ad_copy"]);
    case "social_pack":
      return mockSocial(data as AiTaskData["social_pack"]);
    case "gbp_post":
      return mockGbp(data as AiTaskData["gbp_post"]);
    case "seo_article":
      return mockSeoArticle(data as AiTaskData["seo_article"]);
    case "judge":
      return mockJudge();
    default:
      throw new Error(`Mock provider has no task "${String(task)}"`);
  }
}
